import os
from concurrent.futures import ThreadPoolExecutor, as_completed
from typing import Any, Dict, List

from dotenv import load_dotenv
from langchain_core.messages import AIMessage, ToolMessage
from langgraph.graph import MessagesState
from openai import OpenAI

load_dotenv()

openai_client = OpenAI()
SEARCH_MODEL = os.getenv("OPENAI_SEARCH_MODEL", os.getenv("OPENAI_MODEL", "gpt-5-mini"))


def search_web_with_gpt(query: str) -> str:
    """Execute a web search using the current GPT model's built-in web search tool."""
    try:
        response = openai_client.responses.create(
            model=SEARCH_MODEL,
            tools=[{"type": "web_search"}],
            input=f"Perform a web search and provide factual, up-to-date information and source citations for: {query}",
        )
        return response.output_text
    except Exception as e:
        return f"Error executing search for '{query}': {str(e)}"


def execute_tools(state: MessagesState) -> Dict[str, List[ToolMessage]]:
    """Execute search queries generated by the agent using the current GPT model with web search."""
    messages = state["messages"]
    last_message = messages[-1]

    if not isinstance(last_message, AIMessage) or not last_message.tool_calls:
        return {"messages": []}

    tool_messages = []
    for tool_call in last_message.tool_calls:
        search_queries = tool_call.get("args", {}).get("search_queries", [])

        if not search_queries:
            tool_messages.append(
                ToolMessage(
                    content="No additional search queries provided.",
                    tool_call_id=tool_call["id"],
                    name=tool_call.get("name", "search_tool"),
                )
            )
            continue

        # Focus on top queries for fast, targeted research
        target_queries = search_queries[:2]
        print(f"  🔍 Executing {len(target_queries)} search query(ies) via GPT web search...")
        for i, q in enumerate(target_queries, 1):
            print(f"     [{i}] '{q}'")

        # Execute search queries concurrently for speed
        search_results = {}
        with ThreadPoolExecutor(max_workers=min(len(target_queries), 4)) as executor:
            future_to_query = {
                executor.submit(search_web_with_gpt, q): q for q in target_queries
            }
            for future in as_completed(future_to_query):
                query = future_to_query[future]
                try:
                    res = future.result()
                    search_results[query] = res
                    print(f"  ✅ Completed search for: '{query}'")
                except Exception as exc:
                    search_results[query] = f"Search failed: {exc}"
                    print(f"  ❌ Failed search for: '{query}' ({exc})")

        # Format combined observations for the revisor node
        observations = []
        for i, query in enumerate(target_queries, 1):
            result = search_results.get(query, "No results found.")
            observations.append(f"### [Search Query {i}]: {query}\n{result}")

        combined_content = "\n\n".join(observations)

        tool_messages.append(
            ToolMessage(
                content=combined_content,
                tool_call_id=tool_call["id"],
                name=tool_call.get("name", "search_tool"),
            )
        )

    return {"messages": tool_messages}


if __name__ == "__main__":
    test_result = search_web_with_gpt("AI-powered SOC autonomous startups funding 2026")
    print("Test Search Output:\n", test_result[:300])
